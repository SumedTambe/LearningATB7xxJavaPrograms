package ex_2026.ex_2026_1.ex_02102026;

public class P_063 {
    public static void main(String[] args) {
        //Inverted Right Triangle
        int l=5;
        for(l=5; l>=1; l--){
            for(int s=1; s<=l; s++){
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
